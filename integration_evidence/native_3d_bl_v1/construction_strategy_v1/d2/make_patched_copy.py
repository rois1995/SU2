#!/usr/bin/env python3
"""D2: generate the TEST-ONLY patched copy of CBoundaryLayerMetric (hpp+cpp) in namespace d2patched, included by
UnitTests/SU2_CFD/adaptation/fixtures/native_d2_replay.inc. Production sources are read, never modified.
Runtime switch d2patched::D2TieMode: 0 = production ownership rule (the copy must reproduce native exactly);
1 = candidate fix: canonical (lowest facet index) owner among facets within the existing on-wall rounding bound
d.tolerance of the minimum distance. Thread-local d2patched::D2ForcedFace >= 0 pins the owner facet (candidate fix 2:
ownership supplied by the cut logic's envelope piece). Nothing else in the pointwise law changes.
Also generates a ChordEnvelope copy (namespace d2env) with a read-only Owner(t) accessor."""
import hashlib, json, os, re, sys
REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), *(['..'] * 4)))
HPP = os.path.join(REPO, 'SU2_CFD/include/adaptation/CBoundaryLayerMetric.hpp')
CPP = os.path.join(REPO, 'SU2_CFD/src/adaptation/CBoundaryLayerMetric.cpp')
OUT = os.path.join(REPO, 'UnitTests/SU2_CFD/adaptation/fixtures/native_d2_blmetric_patched.inc')
sha = lambda p: hashlib.sha256(open(p, 'rb').read()).hexdigest()
hpp = open(HPP).read().splitlines(); cpp = open(CPP).read()
body = []
for line in hpp:
    if line.startswith('#pragma once') or line.startswith('#include') or line in (
            'class CConfig;', 'class CGeometry;', 'namespace SU2NativeBoundary2D { struct ReferenceState; }',
            'namespace SU2Native3D { struct ReferenceState; class PlanarReference; class SupportSampler3D; }'):
        continue
    body.append(line)
cpp_lines = [l for l in cpp.splitlines() if not l.startswith('#include')]
cpp = '\n'.join(cpp_lines)
anchor = """      if(distance2<dist2 || (distance2==dist2 && other<id)) {
        id=other;dist2=distance2;std::copy(weights,weights+3,w);std::copy(point,point+3,radial);
      }
    }
"""
assert cpp.count(anchor) == 1, 'ownership anchor not unique'
patch = anchor + """    if(D2TieMode==1) {  // TEST-ONLY D2 candidate: canonical lowest-index owner among rounding-level distance ties.
      const su2double best=sqrt(dist2);
      for(auto other:candidates)if(other<id) {
        su2double weights[3],point[3];const auto distance2=closest(other,weights,point);
        if(sqrt(distance2)<=best+d.tolerance){id=other;dist2=distance2;std::copy(weights,weights+3,w);std::copy(point,point+3,radial);}
      }
    }
"""
patch += """    if(D2ForcedFace>=0){id=(unsigned long)D2ForcedFace;dist2=closest(id,w,radial);}  // TEST-ONLY D2 candidate: owner pinned by the cut logic.
"""
cpp = cpp.replace(anchor, patch)
includes = '\n'.join('#include "../../../../%s"' % p for p in [
    'SU2_CFD/include/adaptation/CBoundaryLayerMetric.hpp', 'Common/include/adaptation/CNativeSupport3D.hpp',
    'Common/include/CConfig.hpp', 'Common/include/parallelization/CPassiveComm.hpp',
    'Common/include/adaptation/CNativeImport2D.hpp', 'Common/include/adaptation/CNativeImport3D.hpp',
    'Common/include/adaptation/CNativeMetric3D.hpp', 'Common/include/adaptation/CNativeChordEnvelope.hpp',
    'SU2_CFD/include/adaptation/ConvexClipping.hpp', 'Common/include/geometry/CGeometry.hpp',
    'Common/include/linear_algebra/blas_structure.hpp', 'SU2_CFD/include/solvers/CSolver.hpp'])
std = '\n'.join('#include <%s>' % s for s in ['algorithm', 'array', 'cmath', 'chrono', 'limits', 'iterator', 'map',
                                             'numeric', 'queue', 'set', 'functional', 'memory', 'stdexcept',
                                             'cstdint', 'string', 'unordered_map', 'vector'])
text = ('// GENERATED by integration_evidence/native_3d_bl_v1/construction_strategy_v1/d2/make_patched_copy.py.\n'
        '// TEST-ONLY patched copy of CBoundaryLayerMetric for the D2 replay; never compiled into production.\n'
        + std + '\n' + includes + '\nnamespace d2patched {\ninline int D2TieMode=0;\ninline thread_local long D2ForcedFace=-1;\n' + '\n'.join(body) + '\n'
        + cpp + '\n}  // namespace d2patched\n')
open(OUT, 'w').write(text)
# TEST-ONLY copy of ChordEnvelope with a read-only owner accessor (namespace d2env), for envelope-pinned ownership.
ENV = os.path.join(REPO, 'Common/include/adaptation/CNativeChordEnvelope.hpp')
OUTE = os.path.join(REPO, 'UnitTests/SU2_CFD/adaptation/fixtures/native_d2_envelope_copy.inc')
env = [l for l in open(ENV).read().splitlines() if not (l.startswith('#pragma once') or l.startswith('#include'))]
env = '\n'.join(env)
hook = '  size_t Comparisons() const{return work;}'
assert env.count(hook) == 1
env = env.replace(hook, '''  // TEST-ONLY: index of the feature owning chord parameter t (Missing outside the covering).
  size_t Owner(long double t) const {
    const auto p=std::lower_bound(pieces.begin(),pieces.end(),t,[](const Piece& p,long double t){return p.hi<t;});
    return (p!=pieces.end() && t>=p->lo) ? p->feature : Missing;
  }
''' + hook)
open(OUTE, 'w').write('// GENERATED by d2/make_patched_copy.py: TEST-ONLY ChordEnvelope copy with an owner accessor.\n'
                      '#include <algorithm>\n#include <array>\n#include <cmath>\n#include <limits>\n#include <stdexcept>\n#include <vector>\n'
                      'namespace d2env {\n' + env + '\n}  // namespace d2env\n')
info = {'hpp': sha(HPP), 'cpp': sha(CPP), 'envelope': sha(ENV), 'generated': sha(OUT), 'generated_envelope': sha(OUTE), 'script': sha(__file__)}
json.dump(info, open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'make_patched_copy.json'), 'w'), indent=1)
print(json.dumps(info, indent=1))
