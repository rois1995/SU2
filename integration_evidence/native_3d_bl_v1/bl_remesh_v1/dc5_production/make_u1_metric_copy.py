#!/usr/bin/env python3
"""DC-5 production re-run: generate the TEST-ONLY U1 admission copy of Common/src/adaptation/CNativeMetric3D.cpp.

The copy is included into one test TU of the test driver only for the U1 run; its definitions then satisfy the
SU2Native3D metric symbols at static link time, so the production engine (CNativeEngine3D, CNativeBoundary3D, ...)
calls it unchanged. With SU2_TEST_U1_ADMISSION unset the copy is the production source verbatim (identical
behaviour). With SU2_TEST_U1_ADMISSION=1 the per-transaction shape admission becomes U1 (user decision 2026-10-22):
every fresh patch must stay positive (J > 0) and must be not worse than the replaced patch (q_min and J_min each
>= the old values, 1e-12 relative slack) unless it passes the absolute gates (q >= .20, J >= .05). Final event
acceptance (ValidateMetricPatch and the engine completion gates) stays absolute and unchanged. Limits (recorded):
first-child absoluteness and LayerConstruct (WP-D, not built) cannot be distinguished inside the metric TU; the height
partitioner's absolute rule (CNativeBoundary3D.cpp) is not switched. Production sources are read, never modified."""
import hashlib, json, os
REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), *(['..'] * 4)))
SRC = os.path.join(REPO, 'Common/src/adaptation/CNativeMetric3D.cpp')
OUT = os.path.join(REPO, 'UnitTests/SU2_CFD/adaptation/fixtures/native_u1_metric_copy.inc')
sha = lambda p: hashlib.sha256(open(p, 'rb').read()).hexdigest()
s = open(SRC).read()
def patch(a, b):
    global s
    assert s.count(a) == 1, a
    s = s.replace(a, b)
patch('#include "../../include/adaptation/CNativeMetric3D.hpp"\n',
      '#include "../../../../Common/include/adaptation/CNativeMetric3D.hpp"\n#include <cstdlib>\n#include <cstring>\n')
patch('''namespace {
bool Same(Point a, Point b) { return a.x == b.x && a.y == b.y && a.z == b.z; }
void Shape(const PatchMetric& m);
}  // namespace''', '''namespace {
bool Same(Point a, Point b) { return a.x == b.x && a.y == b.y && a.z == b.z; }
void Shape(const PatchMetric& m);
// TEST-ONLY U1 switch (SU2_TEST_U1_ADMISSION=1); unset keeps the production rule verbatim.
bool U1Admission() {
  static const bool on = [] { const char* v = std::getenv("SU2_TEST_U1_ADMISSION"); return v && !std::strcmp(v, "1"); }();
  return on;
}
void U1NotWorse(const PatchMetric& before, const PatchMetric& measured) {
  if (!(measured.minimum_scaled_jacobian > 0)) Shape(measured);  // Positivity is never relaxed.
  if (measured.minimum_mean_ratio >= MinimumMeanRatio && measured.minimum_scaled_jacobian >= MinimumScaledJacobian) return;
  if (measured.minimum_mean_ratio >= before.minimum_mean_ratio * (1 - 1e-12) &&
      measured.minimum_scaled_jacobian >= before.minimum_scaled_jacobian * (1 - 1e-12)) return;
  Shape(measured);  // Worse than the replaced patch and below the absolute gates: the production rejection.
}
}  // namespace''')
patch('''  if (require_shape) Shape(result);
  if (stats) {''', '''  if (require_shape && (!U1Admission() || !(result.minimum_scaled_jacobian > 0))) Shape(result);
  if (stats) {''')
patch('''      diagnosis->failure=MetricFailure::Shape;
    }
    Shape(measured);
    long double removed = 0, added = 0;''', '''      diagnosis->failure=MetricFailure::Shape;
    }
    if (U1Admission()) U1NotWorse(before, measured); else Shape(measured);
    long double removed = 0, added = 0;''')
patch('''    measured = MeasureMetricCells(fresh, target, stats, frozen_reuse, true, diagnosis);
    Shape(measured);''', '''    measured = MeasureMetricCells(fresh, target, stats, frozen_reuse, true, diagnosis);
    if (!U1Admission() || !(measured.minimum_scaled_jacobian > 0)) Shape(measured);''')
header = ('// GENERATED by integration_evidence/native_3d_bl_v1/bl_remesh_v1/dc5_production/make_u1_metric_copy.py.\n'
          '// TEST-ONLY copy of Common/src/adaptation/CNativeMetric3D.cpp (production sha %s) with the U1 admission\n'
          '// switch SU2_TEST_U1_ADMISSION; included only for the DC-5 production U1 run, never committed with the include.\n' % sha(SRC))
open(OUT, 'w').write(header + s)
info = {'source': 'Common/src/adaptation/CNativeMetric3D.cpp', 'source_sha256': sha(SRC), 'generated_sha256': sha(OUT), 'script_sha256': sha(__file__)}
json.dump(info, open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'make_u1_metric_copy.json'), 'w'), indent=1)
print(json.dumps(info, indent=1))
